
from __future__ import annotations

import math
from dataclasses import dataclass, field, fields

from .fixed import Q8, UQ


@dataclass(frozen=True)
class Params:
    OBI_EN: bool = True
    OWN_EXCL_EN: bool = True
    TOX_EN: bool = True
    REPLACE_EN: bool = True
    POS_CHECK_EN: bool = True
    VOL_REF: str = "MID"
    BOOK_INVALID_POLICY: str = "HOLD"

    BUS_BYTES: int = 8

    GAMMA: float = 5e-6
    KAPPA: float = 0.25
    V0_TICKS2: int = 625
    VOL_SHIFT: int = 5
    VOL_CLAMP_HALF_TICKS: int = 1023
    VOL_CLAMP_Q8: int = (1 << 17) - 1
    H_SIGMA: float = 0.0

    BASE_ORDER_SIZE: int = 3
    SOFT_INVENTORY_BAND: int = 3
    HARD_POSITION_LIMIT: int = 10
    MAX_ORDER_QTY: int = 10

    TOX_SHIFT: int = 5
    TOX_VMIN: int = 16
    TOX_TH_EIGHTHS: tuple = (4, 5, 6)
    TOX_WIDEN_TICKS: tuple = (0, 1, 3, 0)
    TOX_SIZE_SHIFT: tuple = (0, 0, 1, 0)
    TOX_PULL_LEVEL: int = 3

    def __post_init__(self):
        assert self.VOL_REF in ("MID", "MICRO"), self.VOL_REF
        assert self.BOOK_INVALID_POLICY in ("HOLD", "PULL"), self.BOOK_INVALID_POLICY
        assert len(self.TOX_TH_EIGHTHS) == 3 and list(self.TOX_TH_EIGHTHS) == sorted(self.TOX_TH_EIGHTHS)
        assert all(1 <= t <= 8 for t in self.TOX_TH_EIGHTHS)
        assert len(self.TOX_WIDEN_TICKS) == 4 and len(self.TOX_SIZE_SHIFT) == 4
        assert all(0 <= w <= 63 for w in self.TOX_WIDEN_TICKS)
        assert all(0 <= s <= 3 for s in self.TOX_SIZE_SHIFT)
        assert 1 <= self.TOX_PULL_LEVEL <= 4
        assert 1 <= self.VOL_SHIFT <= 15 and 1 <= self.TOX_SHIFT <= 15
        assert 0 < self.GAMMA and 0 < self.KAPPA and 0 <= self.H_SIGMA
        assert 0 <= self.SOFT_INVENTORY_BAND <= 127 and 1 <= self.BASE_ORDER_SIZE <= 255
        assert 1 <= self.HARD_POSITION_LIMIT <= 127 and 1 <= self.MAX_ORDER_QTY <= 255
        assert self.BUS_BYTES in (1, 2, 4, 8), self.BUS_BYTES
        assert 0 <= self.VOL_CLAMP_HALF_TICKS <= 1023 and 0 <= self.VOL_CLAMP_Q8 <= (1 << 17) - 1
        Q8.check(self.V0_Q8, "V0_Q8")
        UQ(17).check(self.GAMMA_M, "GAMMA_M")
        Q8.check(self.LIQ_Q8, "LIQ_Q8")
        UQ(16).check(self.H_SIGMA_Q8, "H_SIGMA_Q8")
        assert all(Q8.fits(w) for w in self.TOX_WIDEN_Q8)
        assert self.GAMMA_E >= 17, "R's split multiply needs GAMMA_E >= 17"

    @property
    def GAMMA_E(self) -> int:
        e = 0
        while round(self.GAMMA * 2 ** (e + 1)) <= (1 << 17) - 1:
            e += 1
        return e

    @property
    def GAMMA_M(self) -> int:
        return round(self.GAMMA * 2 ** self.GAMMA_E)

    @property
    def LIQ_Q8(self) -> int:
        return round(256 * (2 / self.GAMMA) * math.log1p(self.GAMMA / self.KAPPA))

    @property
    def V0_Q8(self) -> int:
        return self.V0_TICKS2 << 8

    @property
    def H_SIGMA_Q8(self) -> int:
        return round(256 * self.H_SIGMA)

    @property
    def TOX_WIDEN_Q8(self) -> tuple:
        return tuple(t << 8 for t in self.TOX_WIDEN_TICKS)

    def export_sv_pkg(self, name: str = "mm_params_pkg") -> str:
        lines = [f"// Generated by mm_model.params -- do not edit.", f"package {name};"]

        def lp(n, v, w=32):
            lines.append(f"  localparam int unsigned {n} = {w}'d{int(v)};")

        for f in fields(self):
            v = getattr(self, f.name)
            if isinstance(v, bool):
                lines.append(f"  localparam bit {f.name} = 1'b{int(v)};")
            elif isinstance(v, int):
                lp(f.name, v)
            elif isinstance(v, str):
                lines.append(f'  localparam string {f.name} = "{v}";')
            elif isinstance(v, tuple):
                for i, x in enumerate(v):
                    lp(f"{f.name}_{i}", x)
        for n in ("GAMMA_E", "GAMMA_M", "LIQ_Q8", "V0_Q8"):
            lp(n, getattr(self, n))
        for i, x in enumerate(self.TOX_WIDEN_Q8):
            lp(f"TOX_WIDEN_Q8_{i}", x)
        lines.append(f"endpackage : {name}")
        return "\n".join(lines) + "\n"


CKPT2 = Params(OBI_EN=False, OWN_EXCL_EN=False, TOX_EN=False, REPLACE_EN=False)
"""Checkpoint-2 feature set: AS pricing, no OBI, no toxicity, no REPLACE."""

STOCK151 = Params(SOFT_INVENTORY_BAND=6, H_SIGMA=1.0)
"""CPU reference strategy tuned for the stock_151 simulator (trading_simulator), where
the fallback maker quotes 3 sigma wide and customers take the best price whatever it is.
The half-spread is at least one per-heartbeat sigma (half of one 400 ms price update),
and the side that adds to the position is withdrawn only at +-6. In the CPU + accelerator
system both are CPU-side: they change the bank's values, not its format or the RTL."""
